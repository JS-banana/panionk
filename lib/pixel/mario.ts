const FRAMES = [FRAME_RUN1, FRAME_RUN2, FRAME_CROUCH];

export function drawMario(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  frame: 0 | 1 | 2,
  facingRight = true,
) {
  const grid = FRAMES[frame];
  const mp = PAL.marioColors;
  const cols = grid[0].length;

  grid.forEach((row, r) => {
    row.forEach((v, c) => {
      if (!v) return;
      ctx.fillStyle = mp[v];
      const drawC = facingRight ? c : cols - 1 - c;
      ctx.fillRect(
        Math.round(x + drawC * SCALE),
        Math.round(y + r * SCALE),
        SCALE,
        SCALE,
      );
    });
  });
}

export const MARIO_W = 10 * SCALE;
export const MARIO_H = 14 * SCALE;
export { SCALE };
